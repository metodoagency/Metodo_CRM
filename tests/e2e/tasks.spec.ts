test('task editor preserves dirty fields across refetch, rejects stale versions and closes on record navigation', async ({ page }) => {
  test.setTimeout(90000); await signIn(page);
  const headers = { origin: 'http://localhost:5173', 'x-csrf-token': (await (await page.request.get('/api/me')).json()).csrfToken };
  const input = { priority: 'MEDIUM', dueDate: '2028-01-01', recurrence: 'NONE', linkedEntity: null };
  const a = await (await page.request.post('/api/tasks', { headers, data: { ...input, name: `Örnek İlk Görev ${Date.now()}` } })).json();
  const b = await (await page.request.post('/api/tasks', { headers, data: { ...input, name: `Örnek İkinci Görev ${Date.now()}` } })).json();
  await page.goto(`/tasks?task=${a.id}`);
  await page.getByRole('link', { name: b.name, exact: true }).click();
  const panel = page.getByRole('region', { name: 'Görev ayrıntıları', exact: true });
  await expect(panel.getByRole('heading', { name: b.name, exact: true })).toBeVisible();
  await panel.getByRole('button', { name: 'Görevi düzenle', exact: true }).click();
  const editor = page.getByRole('dialog'); const field = editor.getByLabel('Görev adı', { exact: true });
  await field.fill('Örnek Kaybolmayan Taslak');
  await page.clock.install(); await page.clock.fastForward(15001);
  expect((await page.request.patch(`/api/tasks/${b.id}`, { headers, data: { version: 1, changes: { priority: 'HIGH' } } })).ok()).toBe(true);
  const response = page.waitForResponse(reply => reply.url().endsWith(`/api/tasks/${b.id}`) && reply.request().method() === 'GET');
  await page.evaluate(() => window.dispatchEvent(new Event('visibilitychange'))); await response; await page.clock.fastForward(100);
  await expect(field).toHaveValue('Örnek Kaybolmayan Taslak');
  await editor.getByRole('button', { name: 'Kaydet', exact: true }).click();
  await expect(editor.getByRole('alert')).toContainText('Görev değişti'); await expect(field).toHaveValue('Örnek Kaybolmayan Taslak');
  await page.goBack();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.getByRole('heading', { name: a.name, exact: true })).toBeVisible();
  expect((await (await page.request.get(`/api/tasks/${b.id}`)).json()).name).toBe(b.name);
});
