import { buildApp } from './app.js';
import { readConfig } from './config.js';
import { db } from './db.js';
import cron from 'node-cron';
import { dailyJobs } from './jobs.js';
import { refreshBirthdayReminders } from './birthdays.js';
import { refreshContractReminders } from './contract-reminders.js';
import { catchUpPresentationTasks } from './presentation-tasks.js';
const config = readConfig();
const app = await buildApp({ config });
await app.listen({ host: config.HOST, port: config.PORT });
console.log(`Metodo API listening on port ${config.PORT}`);
const birthdayCatchup = refreshBirthdayReminders(db).catch(() => app.log.error('Birthday reminder catch-up failed'));
const contractCatchup = refreshContractReminders(db).catch(() => app.log.error('Contract reminder catch-up failed'));
const presentationCatchup = catchUpPresentationTasks(db).catch(() => app.log.error('Presentation task catch-up failed'));
const job = cron.schedule('0 3 * * *', () => { void dailyJobs().catch(() => app.log.error('Daily maintenance failed')); }, { timezone: 'Europe/Istanbul' });
for (const signal of ['SIGTERM', 'SIGINT']) process.on(signal, () => { void job.stop(); void app.close().then(() => Promise.all([birthdayCatchup, contractCatchup, presentationCatchup])).then(() => db.$disconnect()).then(() => process.exit(0)); });
